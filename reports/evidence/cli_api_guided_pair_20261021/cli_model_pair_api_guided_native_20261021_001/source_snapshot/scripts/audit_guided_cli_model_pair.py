#!/usr/bin/env python3
"""Audit exact S0 restoration, pre-request API proof and original model artifacts."""
import argparse
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
import zipfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cad_cf.cli_model_pair import model_messages
from cad_cf.structural_credit import digest
from scripts.audit_cli_model_pair import audit as audit_model_pair
from scripts.run_guided_cli_model_pair import file_sha


def audit(run):
    config = json.loads((run/'config.json').read_text())
    seed = json.loads((run/'captured_s0.json').read_text())
    pair = json.loads((run/'plan.json').read_text())['pairs'][0]
    probe = json.loads((run/'api_probe.json').read_text())
    prepared = json.loads((run/'prepare/observation.json').read_text())
    assert probe == prepared['generic_api_probe'] and probe['status'] == 'PASS'
    assert seed == prepared['seeds'][pair['id']]
    reference = json.loads((run/'s0_restore_reference.json').read_text())
    assert reference['source_disk_stopped'] and reference['source_disk_sha256'] == config['source_disk_sha256']
    for key in ('seed_sha256', 'seed_state_sha256'):
        assert reference[key] == config[key] == seed[key]
    assert json.loads((run/'source_disk_audit.json').read_text())['unchanged']
    messages = json.loads((run/'model_input.json').read_text())['messages']
    assert messages == model_messages(pair, seed, api_guidance=True)
    events = list(map(json.loads, (run/'trace.jsonl').read_text().splitlines()))
    models = list(map(json.loads, (run/'model_trace.jsonl').read_text().splitlines()))
    # Completion is recorded before the callback can make any model request.
    assert next(r for r in events if r['event'] == 'complete' and r['id'] == 'prepare')['observation'] == prepared
    assert models[0]['event'] == 'request'
    old = json.loads((run/'previous_ledgers.json').read_text())
    root = Path(__file__).resolve().parents[1]
    assert all(file_sha(root/name) == value for name, value in old.items())
    result = audit_model_pair(run)
    if result['status'] == 'PASS':
        artifacts = []
        for branch in ('A', 'B'):
            folder = run/(pair['id']+'-'+branch)
            observation = json.loads((folder/'observation.json').read_text())
            torus = next(o for o in observation['dependency_state']['objects'] if o['name'] == 'Torus')
            bindings = torus['expressions']
            assert torus['type_id'] == 'Part::Torus' and bindings
            with zipfile.ZipFile(folder/'artifact.FCStd') as archive:
                meta = ET.fromstring(archive.read('Document.xml'))
            obj = next(o for o in meta.findall('./ObjectData/Object') if o.get('name') == 'Torus')
            prop = next(p for p in obj.findall('./Properties/Property') if p.get('name') == 'ExpressionEngine')
            expressions = [(e.get('path'), e.get('expression')) for e in prop.findall('.//Expression')]
            assert ['SurfaceArea_mm2', dict(expressions)['SurfaceArea_mm2']] in bindings
            assert len(observation['probes']) == 6
            assert all(p['model_fragment_reexecuted'] is False for p in observation['probes'])
            artifacts.append({'branch':branch, 'native_binding':bindings,
                              'artifact_sha256':observation['artifact_sha256']})
        result.update(native_expression_xml_verified=True, artifacts=artifacts)
    result.update(generic_api_proof_before_requests=True, exact_original_s0_restored=True,
                  original_seed_sha256=seed['seed_sha256'], old_model_ledgers_unchanged=True,
                  guidance_scope='generic API syntax; task geometry formula generated by model',
                  api_probe_sha256=digest(probe))
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--run', type=Path, required=True)
    args = p.parse_args()
    result = audit(args.run)
    (args.run/'verification.json').write_text(json.dumps(result, indent=2, allow_nan=False)+'\n')
    print(json.dumps({k:v for k,v in result.items() if k not in
                     ('candidate_provenance', 'native_artifact_checks', 'budget', 'artifacts')}))


if __name__ == '__main__':
    main()
